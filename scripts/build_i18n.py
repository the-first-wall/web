# --------------------------------------------------------------------------
# i18n.js dictionary parsing
# --------------------------------------------------------------------------
def parse_i18n_js(path: str) -> dict:
    src = _read(path)
    out: dict = {}
    for lang in LANGS:
        m = re.search(r"\n\s*%s\s*:\s*\{" % lang, src)
        if not m:
            raise SystemExit("i18n.js: no %r dictionary found" % lang)
        end = src.index("\n  }", m.end())
        block = src[m.end():end]
        d = {}
        for km in re.finditer(r"(\w+)\s*:\s*\"((?:[^\"\\]|\\.)*)\"", block):
            d[km.group(1)] = _unescape_js(km.group(2))
        out[lang] = d
    return out


def _unescape_js(s: str) -> str:
    return (s.replace("\\\"", "\"")
             .replace("\\'", "'")
             .replace("\\n", "\n")
             .replace("\\t", "\t")
             .replace("\\\\", "\\"))


# --------------------------------------------------------------------------
# Minimal HTML element scanner (enough for well-formed authored pages)
# --------------------------------------------------------------------------
def tokenize(html: str):
    return [(m.start(), m.end(), m.group(0)) for m in TAG_RE.finditer(html)]


def _tagname(raw: str):
    if raw.startswith("<!") or raw.startswith("<?"):
        return None
    m = TAGNAME_RE.match(raw)
    return m.group(1).lower() if m else None


def _is_close(raw: str) -> bool:
    return raw.startswith("</")


def _is_void(raw: str) -> bool:
    name = _tagname(raw)
    if name in VOID_TAGS:
        return True
    # self-closing <tag .../>
    return raw.rstrip().endswith("/>")


def element_end(html: str, tokens, idx: int) -> int:
    """Given the token index of a start tag, return the index just after the
    matching close tag (or just after the start tag for void/self-closing)."""
    raw = tokens[idx][2]
    name = _tagname(raw)
    if name is None or _is_close(raw) or _is_void(raw):
        return tokens[idx][1]
    depth = 1
    j = idx + 1
    while j < len(tokens):
        r = tokens[j][2]
        if not _is_close(r) and _tagname(r) == name and not _is_void(r):
            depth += 1
        elif _is_close(r) and _tagname(r) == name:
            depth -= 1
            if depth == 0:
                return tokens[j][1]
        j += 1
    return tokens[idx][1]


def attrs_of(raw: str) -> dict:
    out = {}
    for m in ATTR_RE.finditer(raw):
        out[m.group(1).lower()] = m.group(2) if m.group(2) is not None else (
            m.group(3) if m.group(3) is not None else m.group(4))
    return out


def has_class(attrs: dict, cls: str) -> bool:
    return cls in (attrs.get("class", "") or "").split()


# --------------------------------------------------------------------------
# Attribute surgery on a start-tag string
# --------------------------------------------------------------------------
def strip_attr(raw: str, name: str) -> str:
    return re.sub(r"\s+%s\s*=\s*(?:\"[^\"]*\"|'[^']*'|[^\s\"'>]+)" % re.escape(name), "", raw)


def set_attr(raw: str, name: str, value: str) -> str:
    value = _html.escape(value, quote=True)
    if re.search(r"\s+%s\s*=" % re.escape(name), raw):
        return re.sub(r"(\s+%s\s*=\s*)(?:\"[^\"]*\"|'[^']*'|[^\s\"'>]+)" % re.escape(name),
                      lambda m: m.group(1) + '"' + value + '"', raw, count=1)
    return raw[:-1].rstrip() + ' %s="%s">' % (name, value)


def _generated_comment(rel: str, lang: str) -> str:
    return ("<!-- %s from src/%s (language: %s). Edit the source, then run: "
            "python scripts/build_i18n.py -->" % (MARK, rel, lang))


# --------------------------------------------------------------------------
# The SEO head
# --------------------------------------------------------------------------
SEO_TOKEN = re.compile(r"[ \t]*<!-- SEO:HEAD\b.*?-->[ \t]*\n?", re.DOTALL)
# tags that only the generator may write: a hand-written copy in a source page would duplicate them
HAND_WRITTEN = re.compile(
    r"<title\b|<meta\b[^>]*\b(?:name=\"(?:description|twitter:[a-z:_]+)\"|property=\"(?:og|article):[a-z:_]+\")"
    r"|<link\b[^>]*\brel=\"(?:canonical|alternate)\"[^>]*\bhreflang=")
LD_BLOCK = re.compile(r'(<script type="application/ld\+json">)(.*?)(</script>)', re.DOTALL)
LD_PLACEHOLDER = re.compile(r"\{\{(?:(t|meta):(\w+)|(lang)|url:(/[^}\s]*))\}\}")


def _attr(value: str) -> str:
    return _html.escape(value, quote=True)


def _json_safe(text: str) -> str:
    """`text` as the inside of a JSON string, safe to put in a <script> block."""
    return json.dumps(text, ensure_ascii=False)[1:-1].replace("</", "<\\/")


def is_policy_page(rel: str) -> bool:
    return rel.startswith(POLICY_PREFIXES)


def _check_source(h: str, rel: str) -> None:
    if len(SEO_TOKEN.findall(h)) != 1:
        raise SystemExit("src/%s: needs exactly one <!-- SEO:HEAD --> marker" % rel)
    if is_policy_page(rel):
        ai = AI_DECLARATION.search(h)
        if ai:
            raise SystemExit("src/%s: policy pages carry no AI-content declaration (operator decision "
                             "2026-10-16), found %r" % (rel, ai.group(0)))
    bad = HAND_WRITTEN.search(SEO_TOKEN.sub("", h))
    if bad:
        raise SystemExit("src/%s: hand-written %r - the title, description, canonical, hreflang, Open Graph "
                         "and Twitter tags come from scripts/page_meta.py" % (rel, bad.group(0)))


def _outside_jsonld(h: str, fn) -> str:
    """Apply `fn` to the page text around its JSON-LD blocks (their URLs are explicit)."""
    out, last = [], 0
    for m in LD_BLOCK.finditer(h):
        out.append(fn(h[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(fn(h[last:]))
    return "".join(out)


def _fill_jsonld(h: str, rel: str, lang: str, dicts: dict) -> str:
    """Resolve the {{...}} placeholders of the page's own JSON-LD blocks, then make sure
    every block is still valid JSON (a typo must fail the build, not silently drop the data)."""
    routes = {e: (e if lang == "en" else g) for _r, e, g in ROUTES}

    def value(m):
        kind, key, is_lang, url = m.group(1), m.group(2), m.group(3), m.group(4)
        if is_lang:
            return lang
        if url:                                    # a page's URL in this language
            if url not in routes:
                raise SystemExit("src/%s: JSON-LD placeholder {{url:%s}} is not a page with a twin" % (rel, url))
            return SITE + routes[url]
        src = dicts[lang] if kind == "t" else page_meta.META[rel][lang]
        if key not in src:
            raise SystemExit("src/%s: JSON-LD placeholder {{%s:%s}} has no %s text" % (rel, kind, key, lang))
        return _json_safe(src[key])

    def block(m):
        body = LD_PLACEHOLDER.sub(value, m.group(2))
        try:
            json.loads(body)
        except ValueError as e:
            raise SystemExit("src/%s: JSON-LD block is not valid JSON (%s)" % (rel, e))
        return m.group(1) + body + m.group(3)
    return LD_BLOCK.sub(block, h)


def _plain(fragment: str) -> str:
    """Visible text of an HTML fragment: tags stripped, entities resolved, whitespace collapsed."""
    return re.sub(r"\s+", " ", _html.unescape(re.sub(r"<[^>]+>", " ", fragment))).strip()


_FAQ_ITEM = re.compile(r"<details\b[^>]*\bfaq-item\b[^>]*>(.*?)</details>", re.S)
_FAQ_SUMMARY = re.compile(r"<summary\b[^>]*>(.*?)</summary>", re.S)
_FAQ_ANSWER = re.compile(r'<div\b[^>]*\bfaq-answer\b[^>]*>(.*?)</div>', re.S)


def faq_jsonld(h: str) -> str:
    """A schema.org FAQPage node derived from the page's own
    ``<details class="faq-item">`` blocks (question = <summary>, answer = .faq-answer).
    Built from the rendered body, so the structured data an answer engine reads can
    never drift from the Q&A a reader sees. Empty string for a page with no FAQ."""
    qa = []
    for item in _FAQ_ITEM.findall(h):
        q, a = _FAQ_SUMMARY.search(item), _FAQ_ANSWER.search(item)
        if not (q and a):
            continue
        qa.append({
            "@type": "Question",
            "name": _plain(q.group(1)),
            "acceptedAnswer": {"@type": "Answer", "text": _plain(a.group(1))},
        })
    if not qa:
        return ""
    page = {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": qa}
    ld = json.dumps(page, ensure_ascii=False, indent=2).replace("</", "<\\/")
    ld = "\n".join("    " + line for line in ld.splitlines())
    return '  <script type="application/ld+json">\n%s\n  </script>\n' % ld


def seo_head(rel: str, lang: str) -> str:
    """The generated head block of `rel` in `lang`."""
    meta = page_meta.META[rel]
    c = meta[lang]
    other = "de" if lang == "en" else "en"
    en, de = SITE + en_url(rel), SITE + de_url(rel)
    own = en if lang == "en" else de
    img = page_meta.IMAGE
    webpage = {
        "@context": "https://schema.org",
        "@type": "WebPage",
        "url": own,
        "name": c["title"],
        "description": c["description"],
        "inLanguage": lang,
        # the site and its publisher are one entity in both languages (same @id as the home page's graph)
        "isPartOf": {"@type": "WebSite", "@id": SITE + "/#website", "name": page_meta.SITE_NAME, "url": SITE + "/"},
        "publisher": {"@type": "Organization", "@id": SITE + "/#organization", "name": page_meta.SITE_NAME, "url": SITE + "/"},
    }
    ld = json.dumps(webpage, ensure_ascii=False, indent=2).replace("</", "<\\/")
    ld = "\n".join("    " + line for line in ld.splitlines())
    lines = [
        "<!-- SEO head: generated by scripts/build_i18n.py from scripts/page_meta.py -->",
        "<title>%s</title>" % _html.escape(c["title"], quote=False),
        '<meta name="description" content="%s">' % _attr(c["description"]),
        '<link rel="canonical" href="%s">' % own,
        '<link rel="alternate" hreflang="en" href="%s">' % en,
        '<link rel="alternate" hreflang="de" href="%s">' % de,
        '<link rel="alternate" hreflang="x-default" href="%s">' % en,
        '<meta property="og:type" content="%s">' % meta["og_type"],
        '<meta property="og:site_name" content="%s">' % _attr(page_meta.SITE_NAME),
        '<meta property="og:title" content="%s">' % _attr(c["title"]),
        '<meta property="og:description" content="%s">' % _attr(c["description"]),
        '<meta property="og:url" content="%s">' % own,
        '<meta property="og:locale" content="%s">' % page_meta.OG_LOCALE[lang],
        '<meta property="og:locale:alternate" content="%s">' % page_meta.OG_LOCALE[other],
        '<meta property="og:image" content="%s">' % img["url"],
        '<meta property="og:image:width" content="%d">' % img["width"],
        '<meta property="og:image:height" content="%d">' % img["height"],
        '<meta property="og:image:alt" content="%s">' % _attr(img["alt"][lang]),
        '<meta name="twitter:card" content="%s">' % meta["twitter_card"],
        '<meta name="twitter:title" content="%s">' % _attr(c["title"]),
        '<meta name="twitter:description" content="%s">' % _attr(c["description"]),
        '<meta name="twitter:image" content="%s">' % img["url"],
        '<meta name="twitter:image:alt" content="%s">' % _attr(img["alt"][lang]),
    ]
    return "".join("  %s\n" % line for line in lines) + '  <script type="application/ld+json">\n%s\n  </script>\n' % ld


# --------------------------------------------------------------------------
# The core transform: source page -> one language page
# --------------------------------------------------------------------------
def render_locale(src_html: str, rel: str, lang: str, dicts: dict) -> str:
    d = dicts[lang]
    en, de = en_url(rel), de_url(rel)
    h = src_html
    _check_source(h, rel)

    # 1) <html lang> + the marker i18n.js reads: the URL decides the language here
    h = re.sub(r"<html\b[^>]*>", '<html lang="%s" data-locale-route="%s">' % (lang, lang), h, count=1)

    # 2) generated-file marker, straight after the doctype
    h = re.sub(r"(<!DOCTYPE[^>]*>)", lambda m: m.group(1) + "\n" + _generated_comment(rel, lang),
               h, count=1, flags=re.IGNORECASE)

    # 3) Handle language sections: keep the page's language, delete the other.
    h = _process_lang_sections(h, lang)

    # 3b) The page's own JSON-LD: resolve its {{...}} placeholders in this language.
    h = _fill_jsonld(h, rel, lang, dicts)

    # 4) Bake data-i18n / data-i18n-aria / data-i18n-title / data-lang-en|de.
    h = _bake_i18n(h, lang, d)

    # 5) Internal links to pages with a twin point at the twin in this language.
    h = _rewrite_links(h, rel, lang)

    # 6) Turn the language toggle into a link to the same page in the other language.
    h = _retarget_toggle(h, lang, en, de)

    # 7) Absolute URLs of the English pages anywhere left (og:url, JSON-LD, twitter)
    #    -> the German URL, for the German page. Done before canonical/hreflang are
    #    inserted so the freshly written alternates are never re-prefixed. Longest
    #    path first, and the match must end at a delimiter so '/articles/' cannot eat
    #    '/articles/01-...' and '/' cannot eat every URL.
    if lang == "de":
        def to_german(text):
            for _rel, e, g in sorted(ROUTES, key=lambda r: -len(r[1])):
                text = re.sub(re.escape(SITE + e) + r'(?=["\'< >\s)?#]|$)', SITE + g, text)
            return text
        h = _outside_jsonld(h, to_german)

    # 8) The SEO head (title, description, canonical, hreflang, Open Graph, Twitter, JSON-LD)
    #    goes where the source has its marker, after the absolute-URL rewrite above so the
    #    alternates it writes are never re-prefixed.
    h = SEO_TOKEN.sub(lambda _m: seo_head(rel, lang) + faq_jsonld(h), h, count=1)

    return h


def _process_lang_sections(h: str, lang: str) -> str:
    drop_class = "lang-section-de" if lang == "en" else "lang-section-en"
    keep_class = "lang-section-en" if lang == "en" else "lang-section-de"
    tokens = tokenize(h)
    # Remove every drop-class element (walk backwards so offsets stay valid).
    removals = []
    keeps = []
    for i, (s, e, raw) in enumerate(tokens):
        if _is_close(raw) or raw.startswith("<!"):
            continue
        if _tagname(raw) not in ("div", "section"):
            continue
        attrs = attrs_of(raw)
        if has_class(attrs, drop_class):
            removals.append((s, element_end(h, tokens, i)))
        elif has_class(attrs, keep_class) and "display:none" in (attrs.get("style", "") or ""):
            keeps.append((s, e, raw))
    for s, e in reversed(removals):
        # also swallow the following newline so no blank line is left behind
        end = e + 1 if e < len(h) and h[e] == "\n" else e
        h = h[:s] + h[end:]
    # Re-tokenize: kept blocks may reference offsets from before the removals.
    if keeps:
        tokens = tokenize(h)
        fixes = []
        for i, (s, e, raw) in enumerate(tokens):
            if _is_close(raw) or raw.startswith("<!"):
                continue
            attrs = attrs_of(raw)
            if has_class(attrs, keep_class) and "display:none" in (attrs.get("style", "") or ""):
                new_style = re.sub(r"\s*display\s*:\s*none\s*;?", "", attrs["style"]).strip(" ;")
                new_raw = strip_attr(raw, "style")
                if new_style:
                    new_raw = set_attr(new_raw, "style", new_style)
                fixes.append((s, e, new_raw))
        for s, e, new_raw in reversed(fixes):
            h = h[:s] + new_raw + h[e:]
    return h


def _bake_i18n(h: str, lang: str, d: dict) -> str:
    tokens = tokenize(h)
    edits = []  # (start, end, replacement, replaces_content)
    for i, (s, e, raw) in enumerate(tokens):
        if _is_close(raw) or raw.startswith("<!"):
            continue
        attrs = attrs_of(raw)
        key = attrs.get("data-i18n")
        akey = attrs.get("data-i18n-aria")
        tkey = attrs.get("data-i18n-title")
        en_c = attrs.get("data-lang-en")
        de_c = attrs.get("data-lang-de")
        if not any((key, akey, tkey, en_c is not None, de_c is not None)):
            continue
        new_raw = raw
        inner = None            # None = the element's content is left alone
        # data-i18n text content (i18n.js sets textContent, so the text is escaped)
        if key and key in d:
            inner = _html.escape(d[key], quote=False)
        # accessible name / tooltip attributes
        if akey and akey in d:
            new_raw = set_attr(new_raw, "aria-label", d[akey])
        if tkey and tkey in d:
            new_raw = set_attr(new_raw, "title", d[tkey])
        # data-lang-* inner HTML
        if en_c is not None or de_c is not None:
            chosen = de_c if (lang == "de" and de_c is not None) else en_c
            if chosen is not None:
                inner = chosen
            new_raw = strip_attr(strip_attr(new_raw, "data-lang-en"), "data-lang-de")
        if new_raw == raw and inner is None:
            continue
        if inner is None or _is_void(raw):
            edits.append((s, e, new_raw, False))           # start tag only: children keep their own edits
        else:
            end = element_end(h, tokens, i)
            close_len = len("</%s>" % _tagname(raw))
            edits.append((s, end - close_len, new_raw + inner, True))
    # An element whose content is replaced swallows anything nested inside it.
    edits.sort(key=lambda x: x[0])
    kept, covered = [], -1
    for s, e, rep, replaces in edits:
        if s < covered:
            continue
        kept.append((s, e, rep))
        if replaces:
            covered = e
    for s, e, rep in reversed(kept):
        h = h[:s] + rep + h[e:]
    return h


def _rewrite_links(h: str, rel: str, lang: str) -> str:
    """Point links to pages that have a twin at the twin in this language. In English
    that is a no-op (the English URLs are the authored ones); fragment-only and
    query-only links are left alone (the pages have no <base>)."""
    orig_to_loc = {e: (e if lang == "en" else g) for _r, e, g in ROUTES}
    src_dir = en_url(rel).rsplit("/", 1)[0] + "/"
    tokens = tokenize(h)
    edits = []
    for s, e, raw in tokens:
        if _is_close(raw) or raw.startswith("<!") or _tagname(raw) not in ("a", "area"):
            continue
        m = re.search(r"\s(href)\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s\"'>]+)", raw)
        if not m:
            continue
        val = m.group(2)
        quote = val[0] if val[0] in "\"'" else ""
        body = val[1:-1] if quote else val
        new = _rewrite_one(body, src_dir, orig_to_loc)
        if new is None or new == body:
            continue
        new_val = (quote + new + quote) if quote else new
        edits.append((s + m.start(2), s + m.end(2), new_val))
    for s, e, rep in reversed(edits):
        h = h[:s] + rep + h[e:]
    return h


def _rewrite_one(body: str, src_dir: str, orig_to_loc: dict):
    b = body.strip()
    if not b or b.startswith(("http://", "https://", "mailto:", "tel:", "//", "data:", "#", "?")):
        return None
    m = re.match(r"^([^?#]*)([?#].*)?$", b)
    path, suffix = m.group(1), m.group(2) or ""
    if not b.startswith("/"):                          # relative -> resolve against the page's directory
        path = posixpath.normpath(posixpath.join(src_dir, path))
        if not path.startswith("/"):
            path = "/" + path
        if m.group(1).endswith("/") and not path.endswith("/"):
            path += "/"
    path = path or "/"
    return orig_to_loc[path] + suffix if path in orig_to_loc else None


def _retarget_toggle(h: str, lang: str, en: str, de: str) -> str:
    """The language toggle (a <button> that i18n.js flips in place) becomes a link
    to the same page in the other language. Same classes, id and inner structure,
    so the styling and i18n.js's label logic carry over unchanged."""
    sibling_lang = "de" if lang == "en" else "en"
    sibling = de if lang == "en" else en
    # the texts i18n.js writes for this language (its step 4)
    label = "🌐 EN" if lang == "en" else "🌐 DE"
    mob = "Language: EN" if lang == "en" else "Sprache: DE"
    title = "Auf Deutsch wechseln (DE)" if lang == "en" else "Switch to English (EN)"
    tokens = tokenize(h)
    edits = []
    for i, (s, e, raw) in enumerate(tokens):
        if _is_close(raw) or raw.startswith("<!"):
            continue
        if _tagname(raw) not in ("button", "a"):
            continue
        attrs = attrs_of(raw)
        if not has_class(attrs, "btn-lang-toggle"):
            continue
        end = element_end(h, tokens, i)
        inner = h[e:end - len("</%s>" % _tagname(raw))]
        if "lang-toggle-text" in inner:
            new_inner = re.sub(r'(<span\b[^>]*\blang-toggle-text\b[^>]*>)[^<]*(</span>)',
                               lambda m: m.group(1) + mob + m.group(2), inner, count=1)
        else:
            new_inner = label
        idattr = ' id="%s"' % _html.escape(attrs["id"], quote=True) if "id" in attrs else ""
        rep = '<a class="%s"%s href="%s" hreflang="%s" lang="%s" title="%s">%s</a>' % (
            _html.escape(attrs.get("class", "btn-lang-toggle"), quote=True), idattr,
            _html.escape(sibling, quote=True), sibling_lang, sibling_lang,
            _html.escape(title, quote=True), new_inner)
        edits.append((s, end, rep))
    for s, e, rep in reversed(edits):
        h = h[:s] + rep + h[e:]
    return h


