def src_path(rel: str) -> str:
    return os.path.join(SRC_DIR, *rel.split("/"))


def out_path(rel: str, lang: str) -> str:
    """English: the page's own URL; German: the same path under de/."""
    parts = rel.split("/")
    return os.path.join(WEB_DIR, *parts) if lang == "en" else os.path.join(WEB_DIR, "de", *parts)


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def expected() -> dict:
    """{absolute path: content} of every file this script owns."""
    dicts = parse_i18n_js(os.path.join(WEB_DIR, "i18n.js"))
    problems = page_meta.problems()
    if set(page_meta.META) != set(PAGES):
        problems.append("scripts/page_meta.py and PAGES list different pages: %s" % sorted(set(page_meta.META) ^ set(PAGES)))
    if problems:
        raise SystemExit("scripts/page_meta.py:\n  " + "\n  ".join(problems))
    want = {}
    for rel in PAGES:
        src_html = _read(src_path(rel))
        for lang in LANGS:
            want[out_path(rel, lang)] = render_locale(src_html, rel, lang, dicts)
    return want


def _orphans(want: dict) -> list:
    """Generated files (carrying the marker) that no page produces any more."""
    found = []
    for dirpath, dirnames, files in os.walk(WEB_DIR):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for f in files:
            p = os.path.join(dirpath, f)
            if f.endswith(".html") and p not in want and build_chrome.is_generated(p):
                found.append(p)
    return found


def build() -> list:
    want = expected()
    for path, text in want.items():
        if not os.path.exists(path) or _read(path) != text:
            _write(path, text)
    for path in _orphans(want):
        os.remove(path)
        d = os.path.dirname(path)
        while d != WEB_DIR and not os.listdir(d):         # leave no empty directories behind
            os.rmdir(d)
            d = os.path.dirname(d)
    return sorted(os.path.relpath(p, WEB_DIR) for p in want)


def check() -> list:
    want = expected()
    stale = [os.path.relpath(p, WEB_DIR) for p, text in want.items()
             if not os.path.exists(p) or _read(p) != text]
    stale += [os.path.relpath(p, WEB_DIR) + " (no longer produced)" for p in _orphans(want)]
    return sorted(stale)


def main(argv) -> int:
    if "--check" in argv:
        stale = check()
        if stale:
            print("STALE generated pages (run: python scripts/build_i18n.py):")
            for s in stale:
                print("  " + s)
            return 1
        print("English and German pages up to date")
        return 0
    written = build()
    print("wrote %d page(s):" % len(written))
    for w in written:
        print("  " + w)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
