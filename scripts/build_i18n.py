#!/usr/bin/env python3
"""
The First Wall — language page builder (English at the root, German under /de/)
==============================================================================

English is the base language and is served at the URLs the site always had
(``/``, ``/manifesto/``, ``/articles/...``). German lives under ``/de/`` and
mirrors them: ``/de/``, ``/de/manifesto/``, ``/de/articles/...``. No generated
page redirects, so every link that was ever shared keeps working, ``/?slot=7``
included (the only redirects are the three legacy legal URLs, see below).

The hand-authored pages live in ``src/`` and hold both languages (the text in the
``data-i18n`` dictionaries of ``i18n.js``, the long texts in ``data-lang-*`` and
``.lang-section-*``). This script reads them and writes ONE language per file:
the English page at its own URL and the German page under ``de/``, each with its
language's text **baked into the raw HTML**, readable with JavaScript disabled,
by crawlers and by link-preview bots. The other language does not ship hidden in
the page.

What is baked
-------------
* ``data-i18n="key"``        -> the key's text in the page's language is written
                                into the element (i18n.js sets textContent, so
                                this is behaviour-identical).
* ``data-i18n-aria="key"``   -> ``aria-label`` is written.
* ``data-i18n-title="key"``  -> ``title`` is written.
* ``data-lang-en`` / ``data-lang-de`` -> the chosen attribute's HTML is written
                                in and the attributes are dropped.
* ``.lang-section-en`` / ``.lang-section-de`` -> only the page's language block
                                survives; the other is removed entirely.

What else a generated page gets
-------------------------------
* ``<html lang="en|de" data-locale-route="en|de">``: i18n.js, which every page
  still loads (``app.js`` uses its ``t()``), takes the language from the URL.
* Its **SEO head**, written where the source page has the ``<!-- SEO:HEAD -->``
  marker, from scripts/page_meta.py: ``<title>``, description, a self
  ``<link rel="canonical">``, ``hreflang`` alternates for ``en``, ``de`` and
  ``x-default`` (-> English), Open Graph (with ``og:locale`` and the other
  language as ``og:locale:alternate``), Twitter card and a ``WebPage`` JSON-LD,
  all in the page's language. The source pages carry none of these by hand (the
  build refuses a hand-written one: it would duplicate the generated tag).
* ``{{t:key}}`` / ``{{meta:key}}`` / ``{{lang}}`` placeholders inside a source
  page's JSON-LD become the dictionary text, the page_meta text or the language
  (the home page's dataset, the articles' item list), ``{{url:/census/}}`` the page's
  URL in the page's language. URLs inside JSON-LD are never rewritten implicitly: the
  site-level entities (WebSite, Organization) keep one identity in both languages.
* Internal links to pages with a twin point at the twin of the page's language
  (German: ``/manifesto/`` -> ``/de/manifesto/``, ``/?slot=7`` -> ``/de/?slot=7``).
* The language toggle becomes a plain link to the same page in the other language
  (same classes, id and inner structure as the button it replaces), so it also
  works without JavaScript and crawlers can follow it.

The legal pages (Impressum, terms, privacy) are generated like every other page,
from ``src/legal/<name>/index.html``: English at ``/legal/<name>/``, German at
``/de/legal/<name>/``. Their old German-only URLs (``/legal/<name>.html``) are
hand-written redirect stubs (``LEGACY_REDIRECTS``); they are not generated and
not in the sitemap. The block pages (``/w1/bNNNN``) are generated by
sync_from_ledger.py and are language-neutral.

Policy pages (``legal/``, ``security/``) carry NO AI-content declaration: they are
reviewed and edited by the human operator (operator decision 2026-10-16). The
build refuses a policy source with the ``ai-content-declaration`` meta, the
AI-GENERATED badge or the end-of-body disclosure. Articles keep theirs.

Deterministic: same ``src/`` + ``i18n.js`` -> byte-identical output. No LLMs, no
network. Every generated file carries ``GENERATED by scripts/build_i18n.py`` right
after the doctype; ``build_chrome.py`` leaves those alone (their chrome is copied
from the source page, which it does stamp).

Usage:
    python scripts/build_i18n.py            # write the English and German pages
    python scripts/build_i18n.py --check    # exit 1 if the committed pages are stale
"""

