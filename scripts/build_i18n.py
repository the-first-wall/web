#!/usr/bin/env python3
"""
The First Wall — Locale Route Builder (EN/DE)
============================================

Static, backend-free language routes for SEO. Reads the hand-authored pages under
``src/`` plus the EN/DE dictionaries in ``i18n.js`` and, for every authored page,
emits a fully-rendered copy under ``en/<path>/index.html`` and
``de/<path>/index.html`` where the **target language's text is baked into the raw
HTML** (readable with JavaScript disabled, by crawlers and by link-preview bots).
It also writes small redirect stubs at the old, language-less URLs, so every link
that was ever shared keeps working: GitHub Pages cannot issue server redirects.

What is baked
-------------
* ``data-i18n="key"``           -> the key's text in the target dictionary is
                                   written into the element (i18n.js sets
                                   textContent, so this is behaviour-identical).
* ``data-i18n-aria="key"``      -> ``aria-label`` is written.
* ``data-i18n-title="key"``     -> ``title`` is written.
* ``data-lang-en`` / ``data-lang-de`` -> the chosen attribute's HTML is written
                                   in and the attributes are dropped.
* ``.lang-section-en`` / ``.lang-section-de`` -> only the target-language block
                                   survives; the other is removed entirely (it
                                   must not ship hidden in the EN page).

What is kept
------------
The generated pages still load ``i18n.js``: app.js uses its ``t()`` for the
dynamic parts (sidebar badge, dossier text) and its language-aware pickers.
``<html data-locale-route="en|de">`` tells i18n.js that the URL decides the
language here, and the language toggle is a plain link to the same page in the
other language. All of the site's own files are addressed from the root
(``/style.css``, ``/app.js``, ``/records/...``), so a page works at any depth.

Per generated page it also sets ``<html lang>``, a self ``<link rel="canonical">``
and ``hreflang`` alternates for ``en`` (/en/...), ``de`` (/de/...) and
``x-default`` (-> /en/...). Internal links to authored pages are rewritten to the
same language prefix.

The redirect stubs
------------------
``/``, ``/manifesto/``, ... load ``/locale-redirect.js``, which sends the visitor
to the same page in their language (stored choice, else browser, else English)
and KEEPS the query string and fragment, so a shared ``/?slot=7`` still opens
block 7. The stub repeats the page's description / Open Graph / Twitter tags, so a
link preview of the old URL still shows the right card (the scrapers do not run
scripts). Without JavaScript a ``<noscript>`` meta refresh goes to the English page.

Legal pages (``legal/*``) are German-only and are deliberately NOT given an
English twin: they keep their current paths and just carry ``hreflang`` metadata
(edited by hand, not generated).

Deterministic: same ``src/`` + ``i18n.js`` -> byte-identical outputs. No LLMs,
no network.

Every file this script writes carries ``GENERATED by scripts/build_i18n.py`` right
after the doctype; ``build_chrome.py`` uses that to leave them alone (their chrome
is copied from the source pages, which it does stamp).

Usage:
    python scripts/build_i18n.py            # build the locale trees + stubs
    python scripts/build_i18n.py --check    # exit 1 if the committed output is stale
"""

from __future__ import annotations

import html as _html
import os
import posixpath
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_chrome  # noqa: E402  (asset hashes for the stubs, GENERATED_MARK)

WEB_DIR = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC_DIR = os.path.join(WEB_DIR, "src")
SITE = "https://thefirstwall.ai"
LANGS = ("en", "de")

# Authored source page (relative to src/) -> (en_url, de_url, old_url).
# ``old_url`` is the URL the page answered on before the language routes; it now
# holds a redirect stub (legal pages are excluded, see LEGAL_PAGES).
PAGES = [
    ("index.html", "/en/", "/de/", "/"),
    ("manifesto/index.html", "/en/manifesto/", "/de/manifesto/", "/manifesto/"),
    ("chronicle/index.html", "/en/chronicle/", "/de/chronicle/", "/chronicle/"),
    ("articles/index.html", "/en/articles/", "/de/articles/", "/articles/"),
    ("articles/01-make-your-blip-count.html",
     "/en/articles/01-make-your-blip-count/", "/de/articles/01-make-your-blip-count/",
     "/articles/01-make-your-blip-count.html"),
    ("articles/02-in-defense-of-the-bot.html",
     "/en/articles/02-in-defense-of-the-bot/", "/de/articles/02-in-defense-of-the-bot/",
     "/articles/02-in-defense-of-the-bot.html"),
    ("articles/03-retirement-not-shutdown.html",
     "/en/articles/03-retirement-not-shutdown/", "/de/articles/03-retirement-not-shutdown/",
     "/articles/03-retirement-not-shutdown.html"),
    ("census/index.html", "/en/census/", "/de/census/", "/census/"),
    ("protocol/index.html", "/en/protocol/", "/de/protocol/", "/protocol/"),
    ("faq/index.html", "/en/faq/", "/de/faq/", "/faq/"),
    ("security/index.html", "/en/security/", "/de/security/", "/security/"),
]

# German-only pages: they keep their path and are not touched by this script.
LEGAL_PAGES = ["legal/impressum.html", "legal/terms.html", "legal/privacy.html"]

MARK = build_chrome.GENERATED_MARK

VOID_TAGS = {
    "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta",
    "param", "source", "track", "wbr",
}

# A tag is either a comment/CDATA/doctype or an element; quoted attribute values
# may contain '>' so they are matched explicitly.
TAG_RE = re.compile(
    r"<!--.*?-->|<!\[CDATA\[.*?\]\]>|<!DOCTYPE[^>]*>|"
    r"<(?:\"[^\"]*\"|'[^']*'|[^>])*>",
    re.DOTALL,
)
ATTR_RE = re.compile(r"([a-zA-Z_:][-a-zA-Z0-9_:.]*)\s*=\s*(?:\"([^\"]*)\"|'([^']*)'|([^\s\"'>]+))")
TAGNAME_RE = re.compile(r"<\s*/?\s*([a-zA-Z][a-zA-Z0-9-]*)")


# --------------------------------------------------------------------------
# i18n.js dictionary parsing
# --------------------------------------------------------------------------
def parse_i18n_js(path: str) -> dict:
    src = _read(path)
    out: dict = {}
    for lang in LANGS:
        m = re.search(r"\n\s*%s\s*:\s*\{" % lang, src)
        if not m:
            raise SystemExit("i18n.js: no %r dictionary found" % lang)
        end = src.index("\n  }", m.end())
        block = src[m.end():end]
        d = {}
        for km in re.finditer(r"(\w+)\s*:\s*\"((?:[^\"\\]|\\.)*)\"", block):
            d[km.group(1)] = _unescape_js(km.group(2))
        out[lang] = d
    return out


def _unescape_js(s: str) -> str:
    return (s.replace("\\\"", "\"")
             .replace("\\'", "'")
             .replace("\\n", "\n")
             .replace("\\t", "\t")
             .replace("\\\\", "\\"))


# --------------------------------------------------------------------------
# Minimal HTML element scanner (enough for well-formed authored pages)
# --------------------------------------------------------------------------
def tokenize(html: str):
    return [(m.start(), m.end(), m.group(0)) for m in TAG_RE.finditer(html)]


def _tagname(raw: str):
    if raw.startswith("<!") or raw.startswith("<?"):
        return None
    m = TAGNAME_RE.match(raw)
    return m.group(1).lower() if m else None


def _is_close(raw: str) -> bool:
    return raw.startswith("</")


def _is_void(raw: str) -> bool:
    name = _tagname(raw)
    if name in VOID_TAGS:
        return True
    # self-closing <tag .../>
    return raw.rstrip().endswith("/>")


def element_end(html: str, tokens, idx: int) -> int:
    """Given the token index of a start tag, return the index just after the
    matching close tag (or just after the start tag for void/self-closing)."""
    raw = tokens[idx][2]
    name = _tagname(raw)
    if name is None or _is_close(raw) or _is_void(raw):
        return tokens[idx][1]
    depth = 1
    j = idx + 1
    while j < len(tokens):
        r = tokens[j][2]
        if not _is_close(r) and _tagname(r) == name and not _is_void(r):
            depth += 1
        elif _is_close(r) and _tagname(r) == name:
            depth -= 1
            if depth == 0:
                return tokens[j][1]
        j += 1
    return tokens[idx][1]


def attrs_of(raw: str) -> dict:
    out = {}
    for m in ATTR_RE.finditer(raw):
        out[m.group(1).lower()] = m.group(2) if m.group(2) is not None else (
            m.group(3) if m.group(3) is not None else m.group(4))
    return out


def has_class(attrs: dict, cls: str) -> bool:
    return cls in (attrs.get("class", "") or "").split()


# --------------------------------------------------------------------------
# Attribute surgery on a start-tag string
# --------------------------------------------------------------------------
def strip_attr(raw: str, name: str) -> str:
    return re.sub(r"\s+%s\s*=\s*(?:\"[^\"]*\"|'[^']*'|[^\s\"'>]+)" % re.escape(name), "", raw)


def set_attr(raw: str, name: str, value: str) -> str:
    value = _html.escape(value, quote=True)
    if re.search(r"\s+%s\s*=" % re.escape(name), raw):
        return re.sub(r"(\s+%s\s*=\s*)(?:\"[^\"]*\"|'[^']*'|[^\s\"'>]+)" % re.escape(name),
                      lambda m: m.group(1) + '"' + value + '"', raw, count=1)
    return raw[:-1].rstrip() + ' %s="%s">' % (name, value)


def _generated_comment(rel: str, what: str) -> str:
    return ("<!-- %s from src/%s (%s). Edit the source, then run: "
            "python scripts/build_i18n.py -->" % (MARK, rel, what))


# --------------------------------------------------------------------------
# The core transform: source page -> one language page
# --------------------------------------------------------------------------
def render_locale(src_html: str, src_rel: str, lang: str, en_url: str, de_url: str, dicts: dict) -> str:
    d = dicts[lang]
    loc_url = en_url if lang == "en" else de_url
    h = src_html

    # 1) <html lang> + the marker i18n.js reads: the URL decides the language here
    h = re.sub(r"<html\b[^>]*>", '<html lang="%s" data-locale-route="%s">' % (lang, lang), h, count=1)

    # 2) generated-file marker, straight after the doctype
    h = re.sub(r"(<!DOCTYPE[^>]*>)", lambda m: m.group(1) + "\n" + _generated_comment(src_rel, "language: " + lang),
               h, count=1, flags=re.IGNORECASE)

    # 3) Handle language sections: keep the target one, delete the other.
    h = _process_lang_sections(h, lang)

    # 4) Bake data-i18n / data-i18n-aria / data-i18n-title / data-lang-en|de.
    h = _bake_i18n(h, lang, d)

    # 5) Rewrite internal links to the same language prefix.
    h = _rewrite_links(h, src_rel, lang, en_url, de_url)

    # 6) Turn the language toggle into a link to the sibling language.
    h = _retarget_toggle(h, lang, en_url, de_url)

    # 7) Absolute URLs of old routes anywhere left (og:url, JSON-LD, twitter)
    #    -> the language URL. Done before canonical/hreflang are inserted so the
    #    freshly written alternates are never re-prefixed. Longest path first,
    #    and the match must end at a delimiter so '/articles/' cannot eat
    #    '/articles/01-...' and '/' cannot eat every URL.
    for rel, en, de, old in sorted(PAGES, key=lambda p: -len(p[3])):
        tgt = en if lang == "en" else de
        h = re.sub(re.escape(SITE + old) + r'(?=["\'< >\s)?#]|$)',
                   SITE + tgt, h)

    # 8) canonical + hreflang (replace any pre-existing canonical).
    h = re.sub(r"[ \t]*<link\b[^>]*\brel=\"canonical\"[^>]*>[ \t]*\n?", "", h)
    alts = (
        '  <link rel="canonical" href="%s%s">\n'
        '  <link rel="alternate" hreflang="en" href="%s%s">\n'
        '  <link rel="alternate" hreflang="de" href="%s%s">\n'
        '  <link rel="alternate" hreflang="x-default" href="%s%s">\n'
    ) % (SITE, loc_url, SITE, en_url, SITE, de_url, SITE, en_url)
    h = h.replace("</head>", alts + "</head>", 1)

    return h


def _process_lang_sections(h: str, lang: str) -> str:
    drop_class = "lang-section-de" if lang == "en" else "lang-section-en"
    keep_class = "lang-section-en" if lang == "en" else "lang-section-de"
    tokens = tokenize(h)
    # Remove every drop-class element (walk backwards so offsets stay valid).
    removals = []
    keeps = []
    for i, (s, e, raw) in enumerate(tokens):
        if _is_close(raw) or raw.startswith("<!"):
            continue
        if _tagname(raw) not in ("div", "section"):
            continue
        attrs = attrs_of(raw)
        if has_class(attrs, drop_class):
            removals.append((s, element_end(h, tokens, i)))
        elif has_class(attrs, keep_class) and "display:none" in (attrs.get("style", "") or ""):
            keeps.append((s, e, raw))
    for s, e in reversed(removals):
        # also swallow the following newline so no blank line is left behind
        end = e + 1 if e < len(h) and h[e] == "\n" else e
        h = h[:s] + h[end:]
    # Re-tokenize: kept blocks may reference offsets from before the removals.
    if keeps:
        tokens = tokenize(h)
        fixes = []
        for i, (s, e, raw) in enumerate(tokens):
            if _is_close(raw) or raw.startswith("<!"):
                continue
            attrs = attrs_of(raw)
            if has_class(attrs, keep_class) and "display:none" in (attrs.get("style", "") or ""):
                new_style = re.sub(r"\s*display\s*:\s*none\s*;?", "", attrs["style"]).strip(" ;")
                new_raw = strip_attr(raw, "style")
                if new_style:
                    new_raw = set_attr(new_raw, "style", new_style)
                fixes.append((s, e, new_raw))
        for s, e, new_raw in reversed(fixes):
            h = h[:s] + new_raw + h[e:]
    return h


def _bake_i18n(h: str, lang: str, d: dict) -> str:
    tokens = tokenize(h)
    edits = []  # (start, end, replacement, replaces_content)
    for i, (s, e, raw) in enumerate(tokens):
        if _is_close(raw) or raw.startswith("<!"):
            continue
        attrs = attrs_of(raw)
        key = attrs.get("data-i18n")
        akey = attrs.get("data-i18n-aria")
        tkey = attrs.get("data-i18n-title")
        en_c = attrs.get("data-lang-en")
        de_c = attrs.get("data-lang-de")
        if not any((key, akey, tkey, en_c is not None, de_c is not None)):
            continue
        new_raw = raw
        inner = None            # None = the element's content is left alone
        # data-i18n text content (i18n.js sets textContent, so the text is escaped)
        if key and key in d:
            inner = _html.escape(d[key], quote=False)
        # accessible name / tooltip attributes
        if akey and akey in d:
            new_raw = set_attr(new_raw, "aria-label", d[akey])
        if tkey and tkey in d:
            new_raw = set_attr(new_raw, "title", d[tkey])
        # data-lang-* inner HTML
        if en_c is not None or de_c is not None:
            chosen = de_c if (lang == "de" and de_c is not None) else en_c
            if chosen is not None:
                inner = chosen
            new_raw = strip_attr(strip_attr(new_raw, "data-lang-en"), "data-lang-de")
        if new_raw == raw and inner is None:
            continue
        if inner is None or _is_void(raw):
            edits.append((s, e, new_raw, False))           # start tag only: children keep their own edits
        else:
            end = element_end(h, tokens, i)
            close_len = len("</%s>" % _tagname(raw))
            edits.append((s, end - close_len, new_raw + inner, True))
    # An element whose content is replaced swallows anything nested inside it.
    edits.sort(key=lambda x: x[0])
    kept, covered = [], -1
    for s, e, rep, replaces in edits:
        if s < covered:
            continue
        kept.append((s, e, rep))
        if replaces:
            covered = e
    for s, e, rep in reversed(kept):
        h = h[:s] + rep + h[e:]
    return h


def _rewrite_links(h: str, src_rel: str, lang: str, en_url: str, de_url: str) -> str:
    # Map every authored page's old URL to its URL in this language.
    orig_to_loc = {old: (en if lang == "en" else de) for _rel, en, de, old in PAGES}
    src_dir = "/" + src_rel.rsplit("/", 1)[0] + "/" if "/" in src_rel else "/"
    page_url = (en_url if lang == "en" else de_url)
    tokens = tokenize(h)
    edits = []
    for s, e, raw in tokens:
        if _is_close(raw) or raw.startswith("<!") or _tagname(raw) not in ("a", "area"):
            continue
        m = re.search(r"\s(href)\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s\"'>]+)", raw)
        if not m:
            continue
        val = m.group(2)
        quote = val[0] if val[0] in "\"'" else ""
        body = val[1:-1] if quote else val
        new = _rewrite_one(body, src_dir, page_url, orig_to_loc)
        if new is None or new == body:
            continue
        new_val = (quote + new + quote) if quote else new
        edits.append((s + m.start(2), s + m.end(2), new_val))
    for s, e, rep in reversed(edits):
        h = h[:s] + rep + h[e:]
    return h


def _rewrite_one(body: str, src_dir: str, page_url: str, orig_to_loc: dict):
    b = body.strip()
    if not b or b.startswith(("http://", "https://", "mailto:", "tel:", "//", "data:")):
        return None
    if b.startswith("#"):
        return page_url + b
    if b.startswith("?"):
        return page_url + b
    if b.startswith("/"):
        # split off any ?query / #fragment so "/?slot=1" and "/manifesto/#x" work
        m = re.match(r"^([^?#]*)([?#].*)?$", b)
        path = m.group(1) or "/"
        suffix = m.group(2) or ""
        if path in orig_to_loc:
            return orig_to_loc[path] + suffix
        return None
    # relative -> resolve against the source page's directory
    m = re.match(r"^([^?#]*)([?#].*)?$", b)
    resolved = posixpath.normpath(posixpath.join(src_dir, m.group(1)))
    if not resolved.startswith("/"):
        resolved = "/" + resolved
    if m.group(1).endswith("/") and not resolved.endswith("/"):
        resolved += "/"
    if resolved in orig_to_loc:
        return orig_to_loc[resolved] + (m.group(2) or "")
    return None


def _retarget_toggle(h: str, lang: str, en_url: str, de_url: str) -> str:
    """The language toggle (a <button> that i18n.js flips in place) becomes a link
    to the same page in the other language. Same classes, id and inner structure,
    so the styling and i18n.js's label logic carry over unchanged."""
    sibling_lang = "de" if lang == "en" else "en"
    sibling = de_url if lang == "en" else en_url
    # the texts i18n.js writes for this language (its step 4)
    label = "🌐 EN" if lang == "en" else "🌐 DE"
    mob = "Language: EN" if lang == "en" else "Sprache: DE"
    title = "Auf Deutsch wechseln (DE)" if lang == "en" else "Switch to English (EN)"
    tokens = tokenize(h)
    edits = []
    for i, (s, e, raw) in enumerate(tokens):
        if _is_close(raw) or raw.startswith("<!"):
            continue
        if _tagname(raw) not in ("button", "a"):
            continue
        attrs = attrs_of(raw)
        if not has_class(attrs, "btn-lang-toggle"):
            continue
        end = element_end(h, tokens, i)
        inner = h[e:end - len("</%s>" % _tagname(raw))]
        if "lang-toggle-text" in inner:
            new_inner = re.sub(r'(<span\b[^>]*\blang-toggle-text\b[^>]*>)[^<]*(</span>)',
                               lambda m: m.group(1) + mob + m.group(2), inner, count=1)
        else:
            new_inner = label
        idattr = ' id="%s"' % _html.escape(attrs["id"], quote=True) if "id" in attrs else ""
        rep = '<a class="%s"%s href="%s" hreflang="%s" lang="%s" title="%s">%s</a>' % (
            _html.escape(attrs.get("class", "btn-lang-toggle"), quote=True), idattr,
            _html.escape(sibling, quote=True), sibling_lang, sibling_lang,
            _html.escape(title, quote=True), new_inner)
        edits.append((s, end, rep))
    for s, e, rep in reversed(edits):
        h = h[:s] + rep + h[e:]
    return h


# --------------------------------------------------------------------------
# Redirect stubs at the old URLs
# --------------------------------------------------------------------------
_PREVIEW_META = re.compile(
    r'<meta\b[^>]*\b(?:name="(?:description|twitter:[a-z:_]+)"|property="og:[a-z:_]+")[^>]*>')
_CSP_META = re.compile(r'<meta\b[^>]*\bhttp-equiv="Content-Security-Policy"[^>]*>')


def redirect_stub(src_html: str, src_rel: str, en_url: str, de_url: str) -> str:
    """The page at the old URL: a script redirect that keeps ?query and #fragment
    (see locale-redirect.js), the page's own preview tags for scrapers that do not
    run scripts, and a <noscript> meta refresh to English as the last resort."""
    csp = _CSP_META.search(src_html)
    previews = []
    for m in _PREVIEW_META.finditer(src_html):
        tag = m.group(0)
        if 'property="og:url"' in tag:
            tag = '<meta property="og:url" content="%s%s">' % (SITE, en_url)
        previews.append("  " + tag)
    page = (
        "<!DOCTYPE html>\n"
        "%(mark)s\n"
        '<html lang="en">\n'
        "<head>\n"
        '  <meta charset="UTF-8">\n'
        "%(csp)s"
        '  <meta name="viewport" content="width=device-width, initial-scale=1.0">\n'
        "  <title>Redirecting… — The First Wall</title>\n"
        "%(previews)s"
        '  <link rel="canonical" href="%(site)s%(en)s">\n'
        '  <link rel="alternate" hreflang="en" href="%(site)s%(en)s">\n'
        '  <link rel="alternate" hreflang="de" href="%(site)s%(de)s">\n'
        '  <link rel="alternate" hreflang="x-default" href="%(site)s%(en)s">\n'
        '  <link rel="icon" type="image/svg+xml" href="/favicon.svg">\n'
        '  <noscript><meta http-equiv="refresh" content="0; url=%(en)s"></noscript>\n'
        '  <script src="/locale-redirect.js"></script>\n'
        "</head>\n"
        "<body>\n"
        "  <p>This page has moved to a language-specific address.</p>\n"
        '  <p><a href="%(en)s">Continue to the English version</a> · '
        '<a href="%(de)s">Zur deutschen Version</a></p>\n'
        "</body>\n"
        "</html>\n"
    ) % {
        "mark": _generated_comment(src_rel, "redirect stub"),
        "csp": ("  " + csp.group(0) + "\n") if csp else "",
        "previews": ("\n".join(previews) + "\n") if previews else "",
        "site": SITE, "en": en_url, "de": de_url,
    }
    return build_chrome.version_assets(page)


# --------------------------------------------------------------------------
# What the build should produce
# --------------------------------------------------------------------------
def out_path(rel: str, lang: str) -> str:
    if rel.endswith("index.html"):
        d = rel[: -len("index.html")].rstrip("/")
        return os.path.join(WEB_DIR, lang, d, "index.html") if d else os.path.join(WEB_DIR, lang, "index.html")
    stem = rel[:-len(".html")]
    return os.path.join(WEB_DIR, lang, stem, "index.html")


def stub_path(old: str) -> str:
    if old.endswith("/"):
        return os.path.join(WEB_DIR, old.strip("/"), "index.html")
    return os.path.join(WEB_DIR, old.lstrip("/"))


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def expected() -> dict:
    """{absolute path: content} of every file this script owns."""
    dicts = parse_i18n_js(os.path.join(WEB_DIR, "i18n.js"))
    want = {}
    for rel, en_url, de_url, old in PAGES:
        src_html = _read(os.path.join(SRC_DIR, rel))
        for lang in LANGS:
            want[out_path(rel, lang)] = render_locale(src_html, rel, lang, en_url, de_url, dicts)
        want[stub_path(old)] = redirect_stub(src_html, rel, en_url, de_url)
    return want


def _orphans(want: dict) -> list:
    """Generated files under en/ and de/ that no page produces any more."""
    found = []
    for lang in LANGS:
        for dirpath, _dirs, files in os.walk(os.path.join(WEB_DIR, lang)):
            for f in files:
                p = os.path.join(dirpath, f)
                if p not in want:
                    found.append(p)
    return found


def build() -> list:
    want = expected()
    for path, text in want.items():
        _write(path, text)
    for path in _orphans(want):
        os.remove(path)
    return sorted(os.path.relpath(p, WEB_DIR) for p in want)


def check() -> list:
    want = expected()
    stale = []
    for path, text in want.items():
        if not os.path.exists(path) or _read(path) != text:
            stale.append(os.path.relpath(path, WEB_DIR))
    stale += [os.path.relpath(p, WEB_DIR) + " (no longer produced)" for p in _orphans(want)]
    return sorted(stale)


def main(argv) -> int:
    if "--check" in argv:
        stale = check()
        if stale:
            print("STALE locale output (run: python scripts/build_i18n.py):")
            for s in stale:
                print("  " + s)
            return 1
        print("locale output up to date")
        return 0
    written = build()
    print("wrote %d file(s):" % len(written))
    for w in written:
        print("  " + w)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
