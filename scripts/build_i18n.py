def en_url(rel: str) -> str:
    """The URL the English page is served on: index.html files by their directory."""
    return "/" + (rel[: -len("index.html")] if rel.endswith("index.html") else rel)


def de_url(rel: str) -> str:
    return "/de" + en_url(rel)


def page_url(rel: str, lang: str) -> str:
    return en_url(rel) if lang == "en" else de_url(rel)


