#!/usr/bin/env python3
"""Stamp the shared site chrome (header + footer) into every page.

The header, the mobile menu and the footer are written once, in
`partials/header.html` and `partials/footer.html`. Every page carries a
generated copy between marker comments, so it is plain static HTML (no
script, no fetch: a crawler or an agent without JavaScript sees the same
navigation as everyone else):

    <!-- SITE:HEADER:START ... -->  ...  <!-- SITE:HEADER:END -->
    <!-- SITE:FOOTER:START ... -->  ...  <!-- SITE:FOOTER:END -->

Usage:
    python scripts/build_chrome.py           rewrite every page in place
    python scripts/build_chrome.py --check   exit 1 if any page has drifted

CI runs `--check`, so a page can never ship a different header than the
others. The slot pages are generated by sync_from_ledger.py from the same
partials (it imports `block()` and `version_assets()` below). The authored pages
live in src/; the English and German pages are generated from them by build_i18n.py
and skipped here.

The same pass versions the site's own scripts and stylesheet:
`app.js` becomes `app.js?v=<hash of its contents>`. GitHub Pages serves
everything with `Cache-Control: max-age=600`, so right after a deploy a
returning visitor's browser can pair the NEW page with a cached OLD script
(and the old script crashed on elements the new page no longer has: the wall
loaded no blocks and ignored clicks). With the hash in the URL a changed file
is always fetched fresh, and each page keeps loading the file it was built
with. Change a script or the stylesheet, run this script, commit the result;
`--check` fails if a page still carries an outdated version.
"""
import hashlib
import os
import re
import sys
import textwrap

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
PARTIALS = os.path.join(ROOT, "partials")
SKIP_DIRS = {".git", "partials", "node_modules", "__pycache__"}
NAMES = ("header", "footer")

# Local files every page loads; their URLs carry a content hash (?v=...).
VERSIONED = ("style.css", "theme.js", "i18n.js", "site.js", "app.js")
_ASSET_REF = re.compile(r'((?:src|href)=")(/|(?:\.\./)*)(%s)(?:\?v=[0-9a-f]+)?(")' % "|".join(re.escape(n) for n in VERSIONED))


def asset_version(name, root=ROOT):
    """First 10 hex digits of the SHA-256 of root/name, or None if it is missing."""
    try:
        with open(os.path.join(root, name), "rb") as fh:
            return hashlib.sha256(fh.read()).hexdigest()[:10]
    except OSError:
        return None


def version_assets(html, root=ROOT):
    """Add/refresh ?v=<hash> on every reference to a VERSIONED file in `html`.
    A reference whose file does not exist under `root` is left as it is."""
    def sub(m):
        ver = asset_version(m.group(3), root)
        return m.group(0) if ver is None else "%s%s%s?v=%s%s" % (m.group(1), m.group(2), m.group(3), ver, m.group(4))
    return _ASSET_REF.sub(sub, html)


def block(name, partials_dir=PARTIALS):
    """The marker-wrapped, indented chrome block for `name` ('header'|'footer')."""
    with open(os.path.join(partials_dir, name + ".html"), encoding="utf-8") as fh:
        body = fh.read().strip("\n")
    tag = "SITE:" + name.upper()
    text = ("<!-- %s:START (generated from partials/%s.html by scripts/build_chrome.py — edit the partial, not this copy) -->\n"
            "%s\n"
            "<!-- %s:END -->") % (tag, name, body, tag)
    return textwrap.indent(text, "  ")


def _pattern(name):
    tag = "SITE:" + name.upper()
    # consume the indentation before the start marker so a run never re-indents
    return re.compile(r"[ \t]*<!-- %s:START\b.*?<!-- %s:END -->" % (re.escape(tag), re.escape(tag)), re.DOTALL)


# build_i18n.py writes this comment into every file it generates (the English pages
# at their own URLs and the German ones under de/). Those are derived from the authored
# pages in src/, which carry the chrome; they are checked by `build_i18n.py --check`.
GENERATED_MARK = "GENERATED by scripts/build_i18n.py"


def is_generated(path):
    with open(path, encoding="utf-8") as fh:
        return GENERATED_MARK in fh.read(600)


def is_redirect_stub(path):
    """A tiny redirect page (meta refresh) carries no site chrome, so it is skipped
    here: it only keeps an old URL working, while the content lives at its canonical
    route. build_i18n._orphans leaves it alone too (it is not a generated language page)."""
    with open(path, encoding="utf-8") as fh:
        return 'http-equiv="refresh"' in fh.read(1500)


def pages():
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for f in sorted(filenames):
            if not f.endswith(".html"):
                continue
            p = os.path.join(dirpath, f)
            if not is_generated(p) and not is_redirect_stub(p):
                yield p


def stamp(html):
    """Return (new_html, missing_marker_names)."""
    missing = []
    for name in NAMES:
        pat = _pattern(name)
        if not pat.search(html):
            missing.append(name)
            continue
        html = pat.sub(lambda _m, n=name: block(n), html, count=1)
    return version_assets(html), missing


def main(argv):
    check = "--check" in argv
    bad = 0
    for path in pages():
        rel = os.path.relpath(path, ROOT)
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
        new, missing = stamp(old)
        if missing:
            print("%s: missing SITE:%s marker(s)" % (rel, "/".join(m.upper() for m in missing)))
            bad += 1
            continue
        if new != old:
            if check:
                print("%s: header/footer or script/stylesheet versions are out of date (run: python scripts/build_chrome.py)" % rel)
                bad += 1
            else:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new)
                print("stamped " + rel)
    if check and not bad:
        print("site chrome: every page matches partials/ and carries current script/stylesheet versions")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
