#!/usr/bin/env python3
"""Stamp the shared site chrome (header + footer) into every page.

The header, the mobile menu and the footer are written once, in
`partials/header.html` and `partials/footer.html`. Every page carries a
generated copy between marker comments, so it is plain static HTML (no
script, no fetch: a crawler or an agent without JavaScript sees the same
navigation as everyone else):

    <!-- SITE:HEADER:START ... -->  ...  <!-- SITE:HEADER:END -->
    <!-- SITE:FOOTER:START ... -->  ...  <!-- SITE:FOOTER:END -->

Usage:
    python scripts/build_chrome.py           rewrite every page in place
    python scripts/build_chrome.py --check   exit 1 if any page has drifted

CI runs `--check`, so a page can never ship a different header than the
others. The slot pages are generated by sync_from_ledger.py from the same
partials (it imports `block()` below).
"""
import os
import re
import sys
import textwrap

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
PARTIALS = os.path.join(ROOT, "partials")
SKIP_DIRS = {".git", "partials", "node_modules", "__pycache__"}
NAMES = ("header", "footer")


def block(name, partials_dir=PARTIALS):
    """The marker-wrapped, indented chrome block for `name` ('header'|'footer')."""
    with open(os.path.join(partials_dir, name + ".html"), encoding="utf-8") as fh:
        body = fh.read().strip("\n")
    tag = "SITE:" + name.upper()
    text = ("<!-- %s:START (generated from partials/%s.html by scripts/build_chrome.py — edit the partial, not this copy) -->\n"
            "%s\n"
            "<!-- %s:END -->") % (tag, name, body, tag)
    return textwrap.indent(text, "  ")


def _pattern(name):
    tag = "SITE:" + name.upper()
    # consume the indentation before the start marker so a run never re-indents
    return re.compile(r"[ \t]*<!-- %s:START\b.*?<!-- %s:END -->" % (re.escape(tag), re.escape(tag)), re.DOTALL)


def pages():
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for f in sorted(filenames):
            if f.endswith(".html"):
                yield os.path.join(dirpath, f)


def stamp(html):
    """Return (new_html, missing_marker_names)."""
    missing = []
    for name in NAMES:
        pat = _pattern(name)
        if not pat.search(html):
            missing.append(name)
            continue
        html = pat.sub(lambda _m, n=name: block(n), html, count=1)
    return html, missing


def main(argv):
    check = "--check" in argv
    bad = 0
    for path in pages():
        rel = os.path.relpath(path, ROOT)
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
        new, missing = stamp(old)
        if missing:
            print("%s: missing SITE:%s marker(s)" % (rel, "/".join(m.upper() for m in missing)))
            bad += 1
            continue
        if new != old:
            if check:
                print("%s: header/footer differ from partials/ (run: python scripts/build_chrome.py)" % rel)
                bad += 1
            else:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new)
                print("stamped " + rel)
    if check and not bad:
        print("site chrome: every page matches partials/")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
